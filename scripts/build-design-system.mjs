// ---------- color math (WCAG) ----------
const lum = (hex) => hex.match(/\w\w/g).map((x) => parseInt(x, 16) / 255)
  .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  .reduce((s, v, i) => s + v * [0.2126, 0.7152, 0.0722][i], 0);
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
// Text on a filled color: white or near-black, whichever has more contrast.
const onColor = (bg) => (ratio("#ffffff", bg) >= ratio("#111827", bg) ? "#ffffff" : "#111827");

// ---------- variables for one mode ----------
function vars(mode) {
  const c = brand.colors[mode], L = dt.levels[mode], s = dt.shadow[mode];
  const v = {
    // shadcn/ui names (https://ui.shadcn.com/docs/theming)
    background: c.bg, foreground: c.ink,
    card: c.surface, "card-foreground": c.ink,
    popover: c.surface, "popover-foreground": c.ink,
    primary: c.primary, "primary-foreground": c.onPrimary,
    secondary: c.primarySoft, "secondary-foreground": c.ink,
    muted: c.code, "muted-foreground": c.muted,
    accent: c.primarySoft, "accent-foreground": c.ink,
    destructive: c.danger, "destructive-foreground": c.onDanger,
    border: c.line, input: c.line, ring: c.primary,
    "chart-1": c.primary, "chart-2": c.success, "chart-3": c.warn, "chart-4": L.mid, "chart-5": L.staff,
    sidebar: c.surface, "sidebar-foreground": c.ink, "sidebar-primary": c.primary, "sidebar-primary-foreground": c.onPrimary,
    "sidebar-accent": c.primarySoft, "sidebar-accent-foreground": c.ink, "sidebar-border": c.line, "sidebar-ring": c.primary,
    // app tokens
    success: c.success, "success-foreground": onColor(c.success, c.ink), "success-soft": c.successSoft,
    warn: c.warn, "warn-foreground": onColor(c.warn, c.ink), "warn-soft": c.warnSoft,
    code: c.code,
    "level-fresh": L.fresh, "level-junior": L.junior, "level-mid": L.mid, "level-senior": L.senior, "level-staff": L.staff,
    "shadow-card": s.card, "shadow-raised": s.raised,
  };
  return Object.entries(v).map(([k, val]) => `  --${k}: ${val};`).join("\n") + `\n  color-scheme: ${mode};`;
}
