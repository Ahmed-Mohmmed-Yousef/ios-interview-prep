// ---------- contrast report ----------
const pairs = [
  ["Body text on page", "ink", "bg", 4.5], ["Body text on card", "ink", "surface", 4.5], ["Grey text on card", "muted", "surface", 4.5],
  ["Button text on primary", "onPrimary", "primary", 4.5], ["Primary as link text on card", "primary", "surface", 4.5],
  ["Text on success", "successFg", "success", 4.5], ["Text on warn", "warnFg", "warn", 4.5],
  ["Success as text on card", "success", "surface", 4.5], ["Warn as text on card", "warn", "surface", 4.5],
  ["Text on soft primary", "ink", "primarySoft", 4.5], ["Text on soft success", "ink", "successSoft", 4.5], ["Text on soft warn", "ink", "warnSoft", 4.5],
  ["Danger as text on card", "danger", "surface", 4.5], ["Border (UI) on card", "line", "surface", 1.3],
];
const levelPairs = ["fresh", "junior", "mid", "senior", "staff"].map((l) => [`Stage color ${l} as text on card`, l, "surface", 4.5]);
function contrastRows(mode) {
  const c = { ...brand.colors[mode], ...dt.levels[mode] };
  c.successFg = onColor(c.success, c.ink); c.warnFg = onColor(c.warn, c.ink);
  return [...pairs, ...levelPairs].map(([label, fg, bg, min]) => {
    const r = ratio(c[fg], c[bg]);
    return { label, fg: c[fg], bg: c[bg], r, min, ok: r >= min };
  });
}
const report = { light: contrastRows("light"), dark: contrastRows("dark") };
const failures = [...report.light, ...report.dark].filter((x) => !x.ok && x.min >= 4.5);

